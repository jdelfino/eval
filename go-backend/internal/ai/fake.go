package ai

import "context"

// FakeMarker is a deterministic substring embedded in every response the
// FakeClient produces. Tests (Go unit and Playwright e2e) assert on this marker
// to confirm the fake provider — rather than a real provider or the StubClient —
// served the request.
const FakeMarker = "FAKE_AI_DETERMINISTIC_SOLUTION"

// FakeClient is a deterministic implementation of Client used for end-to-end
// testing of AI-backed flows without any API key or network access.
//
// It is selected at server startup when the FAKE_AI flag is set (see
// config.AIProviderFake and server.go). Unlike StubClient — which represents the
// "no provider configured" degraded state — FakeClient returns rich, valid,
// deterministic payloads so e2e tests can drive the real handler + UI paths and
// assert on a stable, known result.
type FakeClient struct{}

// GenerateSolution returns a deterministic, valid-looking Python stub solution.
// The returned code embeds FakeMarker so callers can assert the fake provider
// served the request. It never errors and never panics.
func (f *FakeClient) GenerateSolution(_ context.Context, _ GenerateSolutionRequest) (*GenerateSolutionResponse, error) {
	solution := "# " + FakeMarker + "\n" +
		"def solution():\n" +
		"    \"\"\"Deterministic stub generated by the fake AI provider.\"\"\"\n" +
		"    return 42\n"
	return &GenerateSolutionResponse{Solution: solution}, nil
}

// AnalyzeCode returns a deterministic analysis response shaped exactly like a
// real provider's output. When submissions are present it emits a single issue
// covering every submission (Count == len(StudentIDs), as validateResponse
// requires); otherwise it emits no issues. The OverallNote embeds FakeMarker.
func (f *FakeClient) AnalyzeCode(_ context.Context, req AnalyzeRequest) (*AnalyzeResponse, error) {
	total := len(req.Submissions)

	issues := []AnalysisIssue{}
	if total > 0 {
		studentIDs := make([]string, total)
		for i, sub := range req.Submissions {
			studentIDs[i] = sub.UserID
		}
		issues = []AnalysisIssue{
			{
				Title:                      "Fake issue: deterministic analysis",
				Explanation:                "Deterministic issue emitted by the fake AI provider for end-to-end testing.",
				Count:                      total,
				StudentIDs:                 studentIDs,
				RepresentativeStudentID:    req.Submissions[0].UserID,
				RepresentativeStudentLabel: req.Submissions[0].Name,
				Severity:                   IssueSeverityStyle,
			},
		}
	}

	return &AnalyzeResponse{
		Issues:      issues,
		OverallNote: FakeMarker + ": AI analysis served by the fake provider.",
		Summary: AnalysisSummary{
			TotalSubmissions:    total,
			FilteredOut:         0,
			AnalyzedSubmissions: total,
			CompletionEstimate: CompletionEstimate{
				Finished:   total,
				InProgress: 0,
				NotStarted: 0,
			},
		},
	}, nil
}
